"""
DIYhomie — Project Materials, Tools, Product Matching & Purchase Readiness
(Build Document 55).

Turns a project's material list (hi_project_materials, generated by the planner)
into a practical materials workspace: extended purchase statuses + prices,
quantity calculations with an honest basis, substitution checks, a purchase-
readiness gate (safety items can never be silently overridden), in-store
shopping mode and receipt capture.

Collections: hi_receipts, mi_overrides, mi_substitution_checks
Shares: hi_projects, hi_project_materials, hi_measurements, hi_inventory_items, hi_analytics
LLM: gpt-4o vision (receipt OCR) + _llm_json (substitution classification).
"""
import math
import re
import uuid
from datetime import datetime, timezone
from typing import Optional, Callable, List

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel

_db = None
_logger = None
_llm_json: Callable = None
_llm_key: str = ""

USER_STATUSES = ["have_it", "need_it", "need_to_rent", "need_to_borrow", "unsure",
                 "use_alternative", "ordered", "not_required"]
PURCHASE_STATUSES = ["none", "purchased", "delivered", "used", "returned", "unavailable", "substituted"]
RESOLVED_STATUSES = {"have_it", "use_alternative", "not_required"}          # counts as ready
RESOLVED_PURCHASE = {"purchased", "delivered", "used"}
SUB_CLASSES = ["safe_substitute", "verify_first", "not_recommended", "prohibited"]
CALC_BASES = ["measured", "estimated", "user_entered"]
PROHIBITED_KEYWORDS = ["gas line", "gas pipe", "flue", "breaker", "electrical panel", "pressure relief",
                       "tempered glass", "fire-rated", "fire rated", "load bearing", "load-bearing"]


def configure(db, logger, llm_json: Callable, llm_key: str):
    global _db, _logger, _llm_json, _llm_key
    _db, _logger, _llm_json, _llm_key = db, logger, llm_json, (llm_key or "")


def _now():
    return datetime.now(timezone.utc).isoformat()


def _nid():
    return str(uuid.uuid4())


async def _track(user_id, event, meta=None):
    try:
        await _db.hi_analytics.insert_one({"id": _nid(), "user_id": user_id, "event": event, "meta": meta or {}, "at": _now()})
    except Exception:
        pass


async def _project(pid: str, user_id: str) -> dict:
    p = await _db.hi_projects.find_one({"id": pid, "user_id": user_id}, {"_id": 0})
    if not p:
        raise HTTPException(status_code=404, detail="Project not found.")
    return p


async def _material(mid: str, user_id: str) -> dict:
    m = await _db.hi_project_materials.find_one({"id": mid}, {"_id": 0})
    if not m:
        raise HTTPException(status_code=404, detail="Material not found.")
    await _project(m["project_id"], user_id)
    return m


# ---------------------------------------------------------------- name matching (same approach as inventory engine)
STOP = {"the", "a", "an", "of", "for", "and", "with", "set", "pack", "kit", "inch", "in", "ft", "x"}


def _norm(s: str) -> str:
    return re.sub(r"[^a-z0-9 ]", "", (s or "").lower()).strip()


def _tokens(s: str) -> set:
    return {w for w in _norm(s).split() if len(w) >= 3 and w not in STOP}


def _matches(a: str, b: str) -> bool:
    na, nb = _norm(a), _norm(b)
    if not na or not nb:
        return False
    if na in nb or nb in na:
        return True
    return bool(_tokens(a) & _tokens(b))


def _price(v) -> Optional[float]:
    try:
        f = round(float(v), 2)
        return f if f >= 0 else None
    except Exception:
        return None


def _is_resolved(m: dict) -> bool:
    return m.get("user_status") in RESOLVED_STATUSES or m.get("purchase_status") in RESOLVED_PURCHASE


# ================================================================ models
